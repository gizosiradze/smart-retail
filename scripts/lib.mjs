// Shared helpers for the Node scripts (no dependencies; Node 18+; Windows, macOS, Linux).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function arg(name, def) {
  const i = process.argv.indexOf('--' + name);
  return i > 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : def;
}
export const flag = name => process.argv.includes('--' + name);

// Reads KEY=value lines into process.env. Values from the file win, so .env and .env.test never mix.
export function loadEnv(file) {
  const p = path.resolve(ROOT, file);
  if (!fs.existsSync(p)) return false;
  for (const line of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (m) process.env[m[1]] = m[2].replace(/^(["'])(.*)\1$/, '$2');
  }
  return true;
}
export function need(...names) {
  const missing = names.filter(n => !process.env[n]);
  if (missing.length) die(`missing in the env file: ${missing.join(', ')} (see .env.example)`);
}
export function die(msg) { console.error('✗ ' + msg); process.exit(1) }
export const step = t => console.log(`\n\x1b[1m▶ ${t}\x1b[0m`);

// Supabase CLI through npx (no global install, no Docker needed for the commands we use).
// SUPABASE_CLI can point to another executable (used by the tests).
export function supabase(args, { input, quiet } = {}) {
  const cli = process.env.SUPABASE_CLI ? [process.env.SUPABASE_CLI] : ['npx', '--yes', 'supabase@2'];
  const r = spawnSync(cli[0], [...cli.slice(1), ...args], {
    cwd: ROOT, input, encoding: 'utf8', shell: process.platform === 'win32',
    stdio: [input != null ? 'pipe' : 'inherit', quiet ? 'pipe' : 'inherit', 'inherit'],
  });
  if (r.error) die(`could not run the Supabase CLI: ${r.error.message}`);
  if (r.status !== 0) die(`supabase ${args[0]} ${args[1] || ''} failed (exit ${r.status})`);
  return r.stdout || '';
}

export function writeConfig({ url, anonKey, demoHint = '' }) {
  const file = path.join(ROOT, 'web', 'config.js');
  fs.writeFileSync(file, `// Generated by scripts/write-config.mjs — do not edit by hand.
window.SR_CONFIG = ${JSON.stringify({ url: url.replace(/\/$/, ''), anonKey, demoHint }, null, 2)};
`);
  console.log(`web/config.js -> ${url}`);
}

// A token signed with APP_JWT_SECRET but without a session must reach the database and be refused
// there with SESSION_REQUIRED; anything else means the project does not accept our login tokens.
export async function checkTokens() {
  const b = o => Buffer.from(JSON.stringify(o)).toString('base64url');
  const h = b({ alg: 'HS256', typ: 'JWT' }), p = b({ role: 'authenticated', aud: 'authenticated', exp: Math.floor(Date.now() / 1000) + 60 });
  const t = `${h}.${p}.${crypto.createHmac('sha256', process.env.APP_JWT_SECRET).update(`${h}.${p}`).digest('base64url')}`;
  const r = await fetch(`${process.env.SUPABASE_URL.replace(/\/$/, '')}/rest/v1/rpc/sr_me`, {
    method: 'POST', headers: { apikey: process.env.SUPABASE_ANON_KEY, Authorization: 'Bearer ' + t, 'Content-Type': 'application/json' }, body: '{}',
  }).catch(e => ({ text: async () => e.message }));
  const body = await r.text();
  return { ok: body.includes('SESSION_REQUIRED'), body };
}

