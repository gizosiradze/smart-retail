#!/usr/bin/env bash
# Writes web/config.js, the only place the web pages learn where Supabase is.
# Both values are public by design (the anon/publishable key can do nothing without a valid login token).
#
#   SUPABASE_URL=https://xxxx.supabase.co SUPABASE_ANON_KEY=... scripts/write-config.sh
#
# Cloudflare Pages: set the build command to "scripts/write-config.sh", the output directory to "web",
# and SUPABASE_URL / SUPABASE_ANON_KEY as environment variables of the Pages project.
set -euo pipefail
cd "$(dirname "$0")/.."
: "${SUPABASE_URL:?SUPABASE_URL is not set}"
: "${SUPABASE_ANON_KEY:?SUPABASE_ANON_KEY is not set}"
HINT="${DEMO_HINT:-}"
cat > web/config.js <<EOF
// Generated by scripts/write-config.sh — do not edit by hand.
window.SR_CONFIG = {
  url: "${SUPABASE_URL%/}",
  anonKey: "${SUPABASE_ANON_KEY}",
  demoHint: "${HINT}"
};
EOF
echo "web/config.js -> ${SUPABASE_URL%/}"
